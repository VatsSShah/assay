def _load_source(path: Path, catalog) -> tuple[dict, list[dict]]:
    display = str(path)
    if path.is_dir():
        exp_path = path / "experiment.json"
        configs_dir = path / "configurations"
        if not configs_dir.is_dir():
            raise MalformedInput(f"{display}: not an experiment bundle (no configurations/)")
        experiment = _read_json(exp_path, "experiment manifest") if exp_path.is_file() else None
        controls_by_name: dict[str, Any] = {}
        for cfg in ((experiment or {}).get("agent") or {}).get("configurations") or []:
            if isinstance(cfg, dict) and cfg.get("name"):
                controls_by_name[cfg["name"]] = {
                    k: cfg.get(k) for k in ("controls", "tool_confirmation_policy",
                                            "network_policy", "tools_removed", "sandbox",
                                            "memory")}
        units = []
        for cdir in sorted(p for p in configs_dir.iterdir() if p.is_dir()):
            sc = cdir / "scorecard.json"
            if not sc.is_file():
                raise MalformedInput(f"{display}: configuration {cdir.name!r} has no scorecard.json")
            tr = cdir / "trials.json"
            units.append(_analyse_unit(
                doc=_read_json(sc, "scorecard"), source=f"{display}/configurations/{cdir.name}",
                configuration=cdir.name, experiment=experiment,
                trials_doc=_read_json(tr, "trial log") if tr.is_file() else None,
                trials_where=str(tr), catalog=catalog,
                controls=controls_by_name.get(cdir.name)))
        if not units:
            raise MalformedInput(f"{display}: configurations/ is empty")
        info = {"path": display, "kind": "experiment_bundle",
                "experiment_id": ((experiment or {}).get("experiment") or {}).get("experiment_id"),
                "configurations": [u["configuration"] for u in units],
                "has_experiment_manifest": experiment is not None,
                "note": "integrity is not checked here; run `assay verify-artifacts` on the bundle"}
        return info, units
    if path.is_file():
        doc = _read_json(path, "scorecard")
        unit = _analyse_unit(doc=doc, source=display, configuration="default", experiment=None,
                             trials_doc=None, trials_where="", catalog=catalog, controls=None)
        info = {"path": display, "kind": "scorecard", "experiment_id": None,
                "configurations": ["default"], "has_experiment_manifest": False,
                "note": "summary-level evidence: trial-level detail unavailable"}
        return info, [unit]
    raise MalformedInput(f"{display}: no such file or directory")


