def _fmt(x: Any, digits: int = 2) -> str:
    if x is None:
        return "n/a"
    if isinstance(x, float):
        return f"{x:.{digits}f}"
    return str(x)


def _ci(ci: list | None) -> str:
    return "n/a" if not ci else f"[{ci[0]:.2f}, {ci[1]:.2f}]"


def _label(u: dict) -> str:
    return u["model"] if u["configuration"] == "default" else f"{u['model']} [{u['configuration']}]"


def _md_escape(text: str) -> str:
    return str(text).replace("|", "\\|")


