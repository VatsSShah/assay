def analyze_paths(paths: Iterable[str | Path]) -> dict[str, Any]:
    """Analyse experiment bundles and/or bare scorecards. Deterministic for fixed inputs."""
    paths = [Path(p) for p in paths]
    if not paths:
        raise UsageError("analyze needs at least one experiment directory or scorecard")
    catalog = _catalog()
    sources, units = [], []
    for p in paths:
        info, found = _load_source(p, catalog)
        sources.append(info)
        units.extend(found)
    units.sort(key=lambda u: (str(u["model"]), u["configuration"], u["source"]))
    problems = [f"{u['model']} [{u['configuration']}]: {p}" for u in units for p in u["problems"]]
    return {
        "schema": SCHEMA,
        "what_this_is": WHAT_THIS_IS,
        "does_not_establish": list(DOES_NOT_ESTABLISH),
        "low_confidence_threshold_n": LOW_CONFIDENCE_N,
        "interval": "Wilson score interval, 95% (z = 1.96), via scoring.wilson_ci",
        "sources": sources,
        "units": units,
        "pooled_per_task": _pooled(units),
        "comparison": _comparison(units),
        "pairwise": _pairwise(units),
        "controls_comparison": _controls(units),
        "controls_note": CONTROLS_NOTE,
        "problems": problems,
    }


