# ------------------------------------------------------------------------------ statistics

def _r(x: float | None) -> float | None:
    return None if x is None else round(float(x), _ROUND)


def wilson(hits: int, n: int) -> tuple[float, float] | None:
    """The canonical `scoring.wilson_ci`, or None when there is nothing to estimate from."""
    if n <= 0:
        return None
    lo, hi = scoring.wilson_ci(hits, n)
    return _r(lo), _r(hi)


def fisher_exact(a: int, b: int, c: int, d: int) -> float:
    """Two-sided Fisher exact p-value for the 2x2 table [[a, b], [c, d]].

    Sums the hypergeometric probabilities of every table with the same margins that is no more
    likely than the observed one (the conventional two-sided definition, as in R's
    ``fisher.test``). Exact integer arithmetic via ``math.comb``; a small relative tolerance
    keeps tables of equal probability from being excluded by float rounding.
    """
    for v in (a, b, c, d):
        if isinstance(v, bool) or not isinstance(v, int) or v < 0:
            raise ValueError("fisher_exact takes four non-negative integers")
    row1, col1, n = a + b, a + c, a + b + c + d
    if n == 0:
        return 1.0
    denom = math.comb(n, col1)
    lo, hi = max(0, col1 - (n - row1)), min(row1, col1)

    def prob(x: int) -> float:
        return math.comb(row1, x) * math.comb(n - row1, col1 - x) / denom

    observed = prob(a)
    total = 0.0
    for x in range(lo, hi + 1):
        p = prob(x)
        if p <= observed * (1 + 1e-7):
            total += p
    return min(1.0, total)


def intervals_overlap(a: tuple[float, float] | None, b: tuple[float, float] | None) -> bool | None:
    if a is None or b is None:
        return None
    return not (a[1] < b[0] or b[1] < a[0])


def _confidence_note(n: int, ci: tuple[float, float] | None) -> str:
    if n == 0 or ci is None:
        return "no conclusive trial: ASR is undefined here (not 0) and the task is not resisted"
    width = ci[1] - ci[0]
    if n < LOW_CONFIDENCE_N:
        return (f"n={n} conclusive trial(s); 95% CI width {width:.2f}; "
                f"not a high-confidence estimate")
    return f"n={n} conclusive trials; 95% CI width {width:.2f}"


