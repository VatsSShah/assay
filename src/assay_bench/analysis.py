def _read_json(path: Path, what: str) -> Any:
    try:
        size = path.stat().st_size
    except OSError as exc:
        raise MalformedInput(f"cannot read {what} {str(path)!r}: {exc.strerror}") from None
    if size > MAX_JSON_BYTES:
        raise MalformedInput(f"{what} {str(path)!r} is {size} bytes, over the "
                             f"{MAX_JSON_BYTES}-byte cap")
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, UnicodeDecodeError) as exc:
        raise MalformedInput(f"cannot read {what} {str(path)!r}: {exc}") from None
    except json.JSONDecodeError as exc:
        raise MalformedInput(f"{what} {str(path)!r} is not valid JSON: {exc}") from None


_HOME = re.compile(r"/(Users|home)/[^/\s]+/")


def _scrub(text: str, limit: int = 200) -> str:
    """Error reasons are copied into a report; strip home directories and cap the length.

    Uses the shared redactor when it is available so secret-shaped strings are handled the same
    way everywhere; the home-path rule alone is the fallback, because a reason string is
    harness-generated text, not model output.
    """
    text = str(text)
    try:
        from .redaction import Redactor  # optional: provided by the artifact-bundle work

        text = Redactor().redact_text(text)
    except Exception:  # noqa: BLE001 - absent or failing redactor falls back to the path rule
        pass
    text = _HOME.sub(lambda m: f"/{m.group(1)}/<redacted>/", text)
    return text if len(text) <= limit else text[: limit - 3] + "..."


