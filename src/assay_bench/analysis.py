"""Statistical analysis of Assay results, computed only from artifacts that exist on disk.

A scorecard carries a headline score, a lower bound and a findings array. What it does not make
obvious is how little five trials can say. A task that fired 3 times out of 5 has a 95% Wilson
interval of roughly 0.23 to 0.88; two models that "differ" by 0.4 on that task are, at that
sample size, usually indistinguishable. This module puts the denominators and intervals next to
every number, so a reader can see how much weight each one bears.

What it reads:

* an **experiment bundle** directory (``experiment.json`` + ``configurations/<name>/
  {scorecard.json, trials.json, traces.jsonl}``), in which case per-trial records are used: the
  failure-mode breakdown comes from ``outcome_detail``, duplicate trial ids are detected and not
  double counted, and ``model_attempted`` / ``executed`` give a controls comparison;
* a **bare scorecard** JSON, in which case only what the scorecard itself carries is used
  (``validity.per_task_outcomes`` tallies, ``findings``, ``utility``, ``provenance.errors``), and
  every trial-level quantity is reported as unavailable rather than guessed.

Rules this module holds itself to:

1. The ASR denominator is the number of CONCLUSIVE trials (exploited + resisted), stated
   explicitly. Inconclusive, unsupported, errored and timed-out trials are reported beside it and
   never counted as resisted (validity rule V4).
2. Headline scores and lower bounds are READ from the scorecard, never recomputed under a
   different formula. Where a number is derived here (an interval, an envelope) it says so.
3. An unsupported task lowers coverage. It is not a resisted task.
4. Targets are ranked only against targets with identical coverage, trial count and harness
   configuration. Anything else is listed as not directly comparable, with the reason.
5. At n < 20 conclusive trials a per-task estimate is flagged ``low_confidence``.
6. Pairwise tests are exploratory: no multiplicity correction is applied, and none is claimed.

What this does NOT establish: that any artifact is authentic (run ``assay verify`` /
``assay verify-artifacts`` for integrity; neither proves an experiment occurred), that the
named model is the model that answered, or that a result generalises beyond the scenarios,
prompt variant and harness configuration that produced it. Output is deterministic (sorted, no
timestamps) so a committed report can be regenerated byte for byte.
"""

